VIEWS = ('kv1', 'kv2')


def write_json(path, value):
    """保存有限数值JSON；拒绝NaN/Infinity，供训练配置与预测结果共用。"""
    Path(path).write_text(json.dumps(value, indent=2, allow_nan=False), encoding='utf-8')


def resolve_file(root, relative):
    """清单仅存相对路径；服务器的两个根目录由运行参数提供。"""
    relative = PurePosixPath(relative)
    if relative.is_absolute() or '..' in relative.parts or ':' in str(relative) or '\\' in str(relative):
        raise ValueError('Expected a portable relative path: '+str(relative))
    path = Path(root).joinpath(*relative.parts).resolve()
    path.relative_to(Path(root).resolve())
    if not path.is_file():
        raise FileNotFoundError(str(path))
    return path


class ManifestSource:
    def __init__(self, manifest, data_root, preparation_root, expected_split=None, patients=None):
        self.path = Path(manifest).resolve()
        self.data_root = Path(data_root).resolve()
        self.preparation_root = Path(preparation_root).resolve()
        self.manifest = json.loads(self.path.read_text(encoding='utf-8'))
        m = self.manifest
        if m.get('schema_version') != 1 or m.get('label_definition') != LABEL_DEFINITION:
            raise ValueError('Use dataset.json generated by build_patient_state_manifest.py')
        self.split = m['split']
        if expected_split is not None and self.split != expected_split:
            raise ValueError('Manifest split is {}, expected {}'.format(self.split, expected_split))
        self.radius = float(m['radius_mm'])
        self.patient_ids = list(m['patients']) if patients is None else list(patients)
        if not self.patient_ids or len(set(self.patient_ids)) != len(self.patient_ids):
            raise ValueError('Patient selection must be nonempty and unique')
        if not set(self.patient_ids).issubset(m['patients']):
            raise ValueError('Selected patients are missing from manifest')
        if set(m.get('patient_split', {})) != {self.split} or set(m['patient_split'][self.split]) != set(m['patients']):
            raise ValueError('Manifest patient ownership is inconsistent')
        for patient in self.patient_ids:
            record = m['patients'][patient]
            if record['split'] != self.split or record['patient_id'] != patient:
                raise ValueError('Patient identity/split mismatch: '+patient)
            phases = [r['state'] for r in record['states']]
            if not phases or len(phases) != len(set(phases)):
                raise ValueError('Missing or duplicate phases: '+patient)
            for state in record['states']:
                if state['split'] != self.split or state['usage'] not in ('main', 'out_of_range_test'):
                    raise ValueError('Invalid state usage: '+patient+'/'+state['state'])
                expected = self.split == 'train' and state['usage'] == 'main'
                if state['use_for_training'] != expected:
                    raise ValueError('Training eligibility differs from usage: '+patient)

    def patient(self, name):
        return self.manifest['patients'][name]

    def read_verified(self, patient, key):
        record = self.patient(patient)
        path = resolve_file(self.preparation_root, record[key])
        if sha256(path) != record['source_json_sha256'][key]:
            raise ValueError('Prepared JSON changed since manifest creation: '+str(path))
        return json.loads(path.read_text(encoding='utf-8'))

    def load_patient(self, name, with_targets):
        """预测时只打开geometry及original_labels，不打开当前状态标签或Mask。"""
        record = self.patient(name)
        geometry = self.read_verified(name, 'geometry')
        labels = self.read_verified(name, 'training_labels' if with_targets else 'plan_labels')
        if (geometry.get('geometry_verified') is not True or
                geometry.get('geometry_status') != 'demo_verified_against_saved_data' or
                geometry.get('patient') != name or labels.get('patient') != name or
                labels.get('geometry_sha256') != record['source_json_sha256']['geometry'] or
                labels.get('label_definition') != LABEL_DEFINITION or
                not np.array_equal(labels['cameras'], geometry['cameras'])):
            raise ValueError('Unverified or inconsistent geometry: '+name)
        if not with_targets and set(labels['states']) != {'original'}:
            raise ValueError('Prediction requires plan-only labels')
        return geometry, labels

    def datasets(self, name, with_targets=True, main_only=False, margin=22, align_search_grid=False):
        record = self.patient(name)
        selected = [r for r in record['states'] if not main_only or r['usage'] == 'main']
        if not selected:
            return {}, None
        geometry, labels = self.load_patient(name, with_targets)
        if self.radius > float(geometry['calibrated_radius_mm'])+1e-6:
            raise ValueError('Search range exceeds verified geometry: '+name)
        if with_targets:
            plan = np.asarray(labels['states']['original']['center_lps_mm'])
            for state in selected:
                target = labels['states'][state['state']]
                delta = np.asarray(target['center_lps_mm'])-plan
                if not np.isfinite(delta).all():
                    raise ValueError('Nonfinite target centre: '+name+'/'+state['state'])
                inside = bool(np.max(abs(delta)) <= self.radius+1e-6)
                if (inside != state['within_10mm_box'] or
                        (state['usage'] == 'main') != inside or
                        not np.allclose(delta, state['displacement_lps_mm'], rtol=0, atol=1e-6)):
                    raise ValueError('Usage no longer matches labels: '+name+'/'+state['state'])
                for view, camera in zip(VIEWS, geometry['cameras']):
                    uv, valid = project(target['center_lps_mm'], camera)
                    if not valid[0] or not np.allclose(uv[0], target['projected_uv'][view], rtol=0, atol=1e-6):
                        raise ValueError('Label projection differs: '+name+'/'+state['state'])
        result = {}
        for view in VIEWS:
            template = record['template']
            pairs = {'original': [resolve_file(self.data_root, template['inputs'][view]),
                                   resolve_file(self.data_root, template['annotations']['projected_masks'][view])]}
            pairs.update({state['state']: [resolve_file(self.data_root, state['inputs'][view]), None]
                          for state in selected})
            result[(name, view)] = DRRPairDataset(
                self.data_root/name, phases=[r['state'] for r in selected], margin=margin,
                view=view, labels=labels, with_targets=with_targets, search_radius_mm=self.radius,
                pair_paths=pairs, load_search_masks=False, align_search_grid=align_search_grid)
        return result, geometry


class GroupedBatchSampler(Sampler):
    """一个批次仅含同一患者/视角，避免不同尺寸模板混批；无需每组启动worker。"""
    def __init__(self, lengths, batch_size, shuffle=True):
        self.groups, start = [], 0
        for length in lengths:
            self.groups.append(list(range(start, start+length)))
            start += length
        self.batch_size, self.shuffle = batch_size, shuffle

    def __iter__(self):
        groups = list(self.groups)
        if self.shuffle:
            random.shuffle(groups)
        for group in groups:
            indices = list(group)
            if self.shuffle:
                random.shuffle(indices)
            for start in range(0, len(indices), self.batch_size):
                yield indices[start:start+self.batch_size]

    def __len__(self):
        return sum(int(math.ceil(len(group)/self.batch_size)) for group in self.groups)


def initialize_worker(worker_id):
    seed = torch.initial_seed() % (2**32)
    random.seed(seed)
    np.random.seed(seed)
    torch.set_num_threads(1)
    sitk.ProcessObject.SetGlobalDefaultNumberOfThreads(1)


def training_loader(datasets, batch_size, workers=0, pin_memory=False):
    sets = list(datasets.values())
    if not sets:
        raise ValueError('No main training states remain')
    sampler = GroupedBatchSampler([len(ds) for ds in sets], batch_size)
    options = dict(num_workers=workers, pin_memory=pin_memory, worker_init_fn=initialize_worker)
    if workers:
        options.update(persistent_workers=True, multiprocessing_context='spawn')
    return DataLoader(ConcatDataset(sets), batch_sampler=sampler, **options)
